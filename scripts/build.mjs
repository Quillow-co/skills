import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const output = 'skills/quillow-custom-block'

async function emit(filename, content) {
  const target = path.join(root, filename)

  if (check) {
    if ((await readFile(target, 'utf8')) !== content) {
      throw new Error(`${filename} is stale; run npm run build`)
    }
  } else {
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, content)
  }
}

const packages = new Set()

for (const name of ['package', 'validate']) {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [`src/${name}.mjs`],
    bundle: true,
    platform: 'node',
    target: 'node22.20',
    format: 'esm',
    write: false,
    metafile: true,
    banner: {
      js: '// Generated by npm run build. See THIRD_PARTY_NOTICES.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
    },
  })

  await emit(`${output}/scripts/${name}.mjs`, result.outputFiles[0].text)

  for (const input of Object.keys(result.metafile.inputs)) {
    if (input.startsWith('node_modules/')) {
      packages.add(input.split('/')[1])
    }
  }
}

let notices = 'Bundled runtime dependencies (generated by npm run build)\n'

for (const name of [...packages].sort()) {
  const base = path.join(root, 'node_modules', name)
  const pkg = JSON.parse(
    await readFile(path.join(base, 'package.json'), 'utf8')
  )
  notices += `\n--- ${name}@${pkg.version} ---\n\n${await readFile(path.join(base, 'LICENSE'), 'utf8')}\n`
}

await emit(`${output}/THIRD_PARTY_NOTICES`, notices)

console.log(
  check
    ? 'Bundles and notices are current.'
    : 'Built standalone scripts and license notices.'
)
